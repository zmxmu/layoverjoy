/**
 * 应用内双语（中文 / English）基础设施。
 *
 * 设计：所有界面文案集中在本文件的 zh/en 词典中；界面通过 L10n.t(key) 取值。
 * [current] 是 Compose 快照状态，切换语言后所有读取它的 Composable 自动重组，
 * 无需重启 Activity；偏好通过 SharedPreferences 持久化，冷启动恢复。
 */
enum class AppLanguage(val tag: String, val label: String) {
    ZH("zh", "中文"),
    EN("en", "English"),
}

object L10n {

    private const val PREFS = "layoverjoy_i18n"
    private const val KEY_LANG = "app_language"

    var current by mutableStateOf(AppLanguage.ZH)
        private set

    /** Application.onCreate 时调用：从本地偏好恢复语言。 */
    @SuppressLint("ApplySharedPref")
    fun init(context: Context) {
        val tag = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getString(KEY_LANG, null)
        current = AppLanguage.entries.firstOrNull { it.tag == tag } ?: AppLanguage.ZH
    }

    /** 切换并持久化语言。 */
    @SuppressLint("ApplySharedPref")
    fun switchTo(context: Context, lang: AppLanguage) {
        current = lang
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .edit().putString(KEY_LANG, lang.tag).commit()
    }

    /** 按当前语言取文案；缺失时回退中文，再回退 key 本身。 */
    fun t(key: String): String =
        (if (current == AppLanguage.EN) EN[key] else null) ?: ZH[key] ?: key

    /** 带占位符的文案：{1}、{2} 依次替换。 */
    fun t(key: String, vararg args: Any?): String {
        var s = t(key)
        args.forEachIndexed { i, a -> s = s.replace("{${i + 1}}", a?.toString() ?: "") }
        return s
    }

